# Programa para cálculo da soma de dois números
print("Digite o primeiro operando:",end='')
a = int(input()) # Aguarda uma entrada do terminal com input() e converte essa entrada para um numero inteiro com int() 
print("Digite o segundo operando:",end='')
b = int(input())
print(f'Resultado da soma: {a+b}') # O f é necessário para possibilitar a utilização das { }


